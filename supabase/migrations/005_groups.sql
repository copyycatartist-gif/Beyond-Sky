-- Auto-generate GRP-### on INSERT
CREATE OR REPLACE FUNCTION public.set_group_number()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  IF NEW.group_number IS NULL OR NEW.group_number = '' THEN
    NEW.group_number := 'GRP-' || lpad(nextval('public.group_sequence')::TEXT, 3, '0');
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER groups_set_group_number
  BEFORE INSERT ON public.groups
  FOR EACH ROW
  EXECUTE FUNCTION public.set_group_number();

CREATE INDEX IF NOT EXISTS idx_groups_group_number ON public.groups(group_number);
CREATE INDEX IF NOT EXISTS idx_groups_status ON public.groups(status);

-- ============================================================
-- Group members join table
-- ============================================================
CREATE TABLE IF NOT EXISTS public.group_members (
  id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  client_id   UUID NOT NULL REFERENCES public.clients(id),
  group_id    UUID NOT NULL REFERENCES public.groups(id),
  date_joined DATE NOT NULL DEFAULT CURRENT_DATE,
  date_left   DATE,          -- NULL = still active in the group
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),

